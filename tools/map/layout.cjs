#!/usr/bin/env node
/* Compile authored map calibration; runtime never loads design files or SciPy. */
const fs=require('node:fs'),path=require('node:path'),root=path.resolve(__dirname,'../..');
const input='design/artwork/world-map-layout.json',output='js/friends/map-layout.js';
function compile(){
 const data=JSON.parse(fs.readFileSync(path.join(root,input))),cross=(a,b,c,k)=>(b[k]-a[k])*(c[k+1]-a[k+1])-(b[k+1]-a[k+1])*(c[k]-a[k]);
 if(data.format!=='waldpost-painted-map-layout'||data.version!==1)throw Error('Unknown map calibration.');
 for(const t of data.triangles){if(new Set(t).size!==3||t.some(i=>!Number.isInteger(i)||!data.anchors[i]))throw Error('Invalid map triangle.');const p=t.map(i=>data.anchors[i]);if(cross(...p,1)*cross(...p,3)<=0)throw Error('Map calibration folds or collapses a triangle.');}
 for(const [id,p]of Object.entries(data.pins)){if(!p[2]||p[0]<64||p[0]>data.canvas[0]-64||p[1]<64||p[1]>data.canvas[1]-64)throw Error('Pin label can leave the map: '+id);}
 const pins=Object.values(data.pins);for(let i=0;i<pins.length;i++)for(let j=0;j<i;j++)if(Math.max(Math.abs(pins[i][0]-pins[j][0]),Math.abs(pins[i][1]-pins[j][1]))*data.minimumBoardWidth/data.canvas[0]<data.pinPixels+8)throw Error('Map pin hit areas overlap.');
 const {canvas,worldExtent,anchors,triangles,pins:positions}=data;
 return `/* Generated by tools/map/layout.cjs from the approved painting's calibration. */
import {EXTRAS} from './world/big/layout.js';
const canvas=${JSON.stringify(canvas)},extent=${JSON.stringify(worldExtent)};
const anchors=${JSON.stringify(anchors)},triangles=${JSON.stringify(triangles)};
const pins=${JSON.stringify(positions)};
export const extraMapPlaces={ibex:{x:EXTRAS.ibex.at[0],z:EXTRAS.ibex.at[1],name:'Zu Steinbock',picture:'ibex'}};
export function mapPin(id){const p=pins[id];if(!p)throw Error('Unknown map pin: '+id);return {x:p[0]/canvas[0],y:p[1]/canvas[1],label:p[2]};}
export function mapPoint(x,z){
 x=Math.max(extent[0],Math.min(extent[2],x));z=Math.max(extent[1],Math.min(extent[3],z));
 for(const t of triangles){const [a,b,c]=t.map(i=>anchors[i]),d=(b[2]-c[2])*(a[1]-c[1])+(c[1]-b[1])*(a[2]-c[2]);
  const u=((b[2]-c[2])*(x-c[1])+(c[1]-b[1])*(z-c[2]))/d,v=((c[2]-a[2])*(x-c[1])+(a[1]-c[1])*(z-c[2]))/d,w=1-u-v;
  if(Math.min(u,v,w)>=-1e-8)return [(u*a[3]+v*b[3]+w*c[3])/canvas[0],(u*a[4]+v*b[4]+w*c[4])/canvas[1]];
 }
 return [(x-extent[0])/(extent[2]-extent[0]),(z-extent[1])/(extent[3]-extent[1])];
}
`;
}
module.exports={compile};
if(require.main===module){try{const value=compile(),file=path.join(root,output);if(process.argv.includes('--check')){if(fs.readFileSync(file,'utf8')!==value)throw Error('Regenerate the painted-map calibration with node tools/map/layout.cjs.');console.log('Painted-map calibration, projection and pin spacing are current.');}else{fs.writeFileSync(file,value);console.log('Wrote calibrated painted-map projection and pin positions.');}}catch(e){console.error(e.message);process.exitCode=1;}}
